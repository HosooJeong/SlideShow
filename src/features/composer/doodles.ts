/**
 * 마카 낙서 아이콘. 각 아이콘은 단위 상자 [-0.5, 0.5]² 안의 폴리라인 묶음(한 획 = 한 폴리라인).
 * 좌표는 직접 그린 것(라이선스 없음). y는 위가 +.
 */
export type DoodlePolyline = [number, number][]
export type DoodleIcon =
  | 'balloon'
  | 'heart'
  | 'star'
  | 'cloud'
  | 'crown'
  | 'sparkle'
  | 'sun'
  | 'duck'
  | 'rattle'
  | 'cake'
  | 'bottle'
  | 'flower'
  | 'moon'
  | 'smile'

const circle = (cx: number, cy: number, r: number, n = 24, from = 0, turns = 1): DoodlePolyline =>
  Array.from({ length: n + 1 }, (_, i) => {
    const a = from + (i / n) * Math.PI * 2 * turns
    return [cx + Math.cos(a) * r, cy + Math.sin(a) * r]
  })

